#requires -Version 5
<#
    Coralink server launcher for a Tailscale tailnet (Windows).

    What it does, in order:
      1. Verifies Node.js (>=24) and the Tailscale CLI are available.
      2. Ensures this machine is connected to the tailnet (tailscale up).
      3. Creates server\.env with strong random secrets on first run.
      4. Installs server dependencies if node_modules is missing.
      5. Starts the Coralink server (loopback only) in a new window.
      6. Publishes it on HTTPS via "tailscale serve" and prints the ts.net link
         you paste into the app's "Server link" field.

    Usage (from an ordinary PowerShell window):
      powershell -ExecutionPolicy Bypass -File .\run-tailscale.ps1
      powershell -ExecutionPolicy Bypass -File .\run-tailscale.ps1 -Stop

    Safe by default: it never deletes data and never touches your existing VPN.
#>

[CmdletBinding()]
param(
    [int]$Port = 8080,
    [string]$Tailnet = "",
    [switch]$Stop
)

$ErrorActionPreference = "Stop"
$ServerDir = Split-Path -Parent $PSScriptRoot   # ...\Coralink\server
$EnvFile   = Join-Path $ServerDir ".env"

function Write-Step($msg)  { Write-Host "==> $msg" -ForegroundColor Cyan }
function Write-Ok($msg)    { Write-Host "    $msg" -ForegroundColor Green }
function Write-Warn($msg)  { Write-Host "    $msg" -ForegroundColor Yellow }

function Test-Cmd($name) {
    return [bool](Get-Command $name -ErrorAction SilentlyContinue)
}

# --- stop path -------------------------------------------------------------
if ($Stop) {
    Write-Step "Stopping Coralink server"
    $conns = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue
    if ($conns) {
        $conns | Select-Object -ExpandProperty OwningProcess -Unique | ForEach-Object {
            Write-Warn "Killing PID $_ listening on $Port"
            Stop-Process -Id $_ -Force
        }
    } else {
        Write-Ok "Nothing is listening on port $Port"
    }
    Write-Step "Removing tailscale serve proxy"
    if (Test-Cmd tailscale) { tailscale serve --bg=false $Port 2>$null | Out-Null }
    Write-Ok "Stopped."
    return
}

# --- prerequisites ---------------------------------------------------------
Write-Step "Checking prerequisites"
if (-not (Test-Cmd node)) {
    throw "Node.js not found. Install Node 24 (https://nodejs.org) and re-run."
}
$nodeMajor = [int]((node -v) -replace 'v','' -split '\.')[0]
if ($nodeMajor -lt 24) {
    throw "Node $((node -v)) is too old. Coralink server needs Node 24 or newer."
}
Write-Ok "Node $((node -v))"

if (-not (Test-Cmd tailscale)) {
    throw "Tailscale CLI not found. Install Tailscale (https://tailscale.com/download) and sign in, then re-run."
}
Write-Ok "Tailscale CLI found"

# --- ensure connected ------------------------------------------------------
Write-Step "Ensuring Tailscale is connected"
$state = (tailscale status --json 2>$null | ConvertFrom-Json).BackendState
if ($state -ne "Running") {
    Write-Warn "Backend is '$state'. Opening browser to log in..."
    tailscale up --login
    Write-Host "    Complete the login, then re-run this script." -ForegroundColor Magenta
    return
}
Write-Ok "Connected (BackendState=Running)"

# --- .env with generated secrets -------------------------------------------
Write-Step "Preparing server\.env"
if (-not (Test-Path $EnvFile)) {
    $jwt  = -join ((48..57) + (97..122) | Get-Random -Count 64 | ForEach-Object { [char]$_ })
    $pep  = -join ((48..57) + (97..122) | Get-Random -Count 64 | ForEach-Object { [char]$_ })
    $dataDir = Join-Path $ServerDir "data"
    $dbPath  = Join-Path $dataDir "coralink.db"
    @(
        "# Coralink server configuration (generated by run-tailscale.ps1)"
        "NODE_ENV=production"
        "HOST=127.0.0.1"
        "PORT=$Port"
        "JWT_SECRET=$jwt"
        "AUTH_PEPPER=$pep"
        "DB_PATH=$dbPath"
        "ALLOWED_ORIGINS=*"
        "MESSAGE_TTL_DAYS=30"
        "WS_MAX_CONNECTIONS=3"
        "LOG_LEVEL=info"
    ) | Set-Content -Encoding UTF8 $EnvFile
    Write-Ok "Created $EnvFile"
} else {
    Write-Ok "Reusing existing $EnvFile"
}

# --- install deps ----------------------------------------------------------
$nm = Join-Path $ServerDir "node_modules"
Write-Step "Installing dependencies"
if (-not (Test-Path $nm)) {
    Push-Location $ServerDir
    npm install --omit=dev
    Pop-Location
    Write-Ok "Dependencies installed"
} else {
    Write-Ok "node_modules already present"
}

# --- start server in its own window ----------------------------------------
Write-Step "Starting Coralink server on 127.0.0.1:$Port"
Push-Location $ServerDir
Start-Process -FilePath "node" `
    -ArgumentList @("--env-file=.env", "src/index.js") `
    -WorkingDirectory $ServerDir -WindowStyle Normal | Out-Null
Pop-Location

# give it a moment then confirm health locally
$healthy = $false
for ($i = 0; $i -lt 10; $i++) {
    try {
        Invoke-RestMethod -Uri "http://127.0.0.1:$Port/health" -TimeoutSec 2 | Out-Null
        $healthy = $true; break
    } catch { Start-Sleep -Milliseconds 700 }
}
if (-not $healthy) {
    Write-Warn "Server did not answer /health yet. Check the new window for errors."
} else {
    Write-Ok "Server is healthy"
}

# --- publish on HTTPS via tailscale serve -----------------------------------
Write-Step "Publishing on HTTPS with 'tailscale serve'"
try {
    tailscale serve --bg $Port 2>&1 | Out-Host
} catch {
    Write-Warn "tailscale serve failed. On older Tailscale try: tailscale serve --bg --https=443 http://127.0.0.1:$Port"
}

$dnsName = (tailscale status --json 2>$null | ConvertFrom-Json).Self.DNSName
$link = if ($dnsName) { "https://$dnsName" } else { "https://<machine>.<tailnet>.ts.net" }

Write-Host ""
Write-Host "=====================================================" -ForegroundColor Green
Write-Host " Coralink is live on your tailnet" -ForegroundColor Green
Write-Host "=====================================================" -ForegroundColor Green
Write-Host "  Server link to paste in the app: $link" -ForegroundColor White
Write-Host ""
Write-Host "  Next steps:"
Write-Host "   1. On every device that will use Coralink, install Tailscale and join the same tailnet."
if ($Tailnet) {
    Write-Host "   2. Invite devices/users to the tailnet at https://login.tailscale.com/admin/machines (or Shared Networks)."
} else {
    Write-Host "   2. Invite devices/users via Tailscale admin -> 'Share a node' / Shared Networks."
}
Write-Host "   3. Open the app, paste the link above into 'Server link', choose a nickname, tap Continue."
Write-Host ""
Write-Host "  To stop later:  powershell -File .\run-tailscale.ps1 -Stop"
Write-Host "=====================================================" -ForegroundColor Green
